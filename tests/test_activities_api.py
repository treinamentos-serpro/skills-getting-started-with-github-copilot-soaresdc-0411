def test_signup_returns_400_for_duplicate_participant(client, activities):
    # Arrange
    activity_name = "Chess Club"
    email = activities[activity_name]["participants"][0]
    original_count = len(activities[activity_name]["participants"])

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 400
    assert response.json()["detail"] == "Student already signed up for this activity"
    assert len(activities[activity_name]["participants"]) == original_count


def test_signup_returns_400_when_activity_is_full(client, activities):
    # Arrange
    activity_name = "Soccer Team"
    activity = activities[activity_name]
    activity["participants"] = [
        f"student-{index}@example.edu"
        for index in range(activity["max_participants"])
    ]
    email = "new-student@example.edu"

    # Act
    response = client.post(
        f"/activities/{activity_name}/signup",
        params={"email": email},
    )

    # Assert
    assert response.status_code == 400
    assert response.json()["detail"] == "Activity is full"
    assert email not in activity["participants"]


